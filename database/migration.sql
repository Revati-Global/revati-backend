-- ==============================================================================
-- REVATI GLOBAL: Master Supabase PostgreSQL Schema & Migration
-- ==============================================================================
-- Rules:
-- 1. All tables have Row Level Security (RLS) enabled with NO public policies.
-- 2. Timestamps are timestamptz with default now().
-- 3. Slugs have unique indexes.
-- 4. status, order, category_id have indexes.
-- 5. Idempotent: safe to run multiple times (IF NOT EXISTS, ON CONFLICT DO NOTHING).
-- ==============================================================================

-- 1. USERS
CREATE TABLE IF NOT EXISTS public."users" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(255) NOT NULL,
  "email" VARCHAR(255) UNIQUE NOT NULL,
  "email_verified_at" TIMESTAMPTZ DEFAULT NULL,
  "password" VARCHAR(255) NOT NULL,
  "phone_number" VARCHAR(255) DEFAULT NULL,
  "image" VARCHAR(255) DEFAULT NULL,
  "remember_token" VARCHAR(100) DEFAULT NULL,
  "created_at" TIMESTAMPTZ DEFAULT now(),
  "updated_at" TIMESTAMPTZ DEFAULT now()
);

-- 2. ROLES
CREATE TABLE IF NOT EXISTS public."roles" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(255) UNIQUE NOT NULL,
  "guard_name" VARCHAR(255) NOT NULL DEFAULT 'web',
  "created_at" TIMESTAMPTZ DEFAULT now(),
  "updated_at" TIMESTAMPTZ DEFAULT now()
);

-- 3. PERMISSIONS
CREATE TABLE IF NOT EXISTS public."permissions" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(255) UNIQUE NOT NULL,
  "guard_name" VARCHAR(255) NOT NULL DEFAULT 'web',
  "created_at" TIMESTAMPTZ DEFAULT now(),
  "updated_at" TIMESTAMPTZ DEFAULT now()
);

-- 4. MODEL_HAS_ROLES
CREATE TABLE IF NOT EXISTS public."model_has_roles" (
  "role_id" BIGINT NOT NULL REFERENCES public."roles"("id") ON DELETE CASCADE,
  "model_type" VARCHAR(255) NOT NULL DEFAULT 'App\\Models\\User',
  "model_id" BIGINT NOT NULL,
  PRIMARY KEY ("role_id", "model_id", "model_type")
);

-- 5. ROLE_HAS_PERMISSIONS
CREATE TABLE IF NOT EXISTS public."role_has_permissions" (
  "permission_id" BIGINT NOT NULL REFERENCES public."permissions"("id") ON DELETE CASCADE,
  "role_id" BIGINT NOT NULL REFERENCES public."roles"("id") ON DELETE CASCADE,
  PRIMARY KEY ("permission_id", "role_id")
);

